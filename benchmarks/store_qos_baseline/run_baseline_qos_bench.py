#!/usr/bin/env python3
import argparse
import csv
import json
import socket
import subprocess
import time
from pathlib import Path


SCENARIOS = (
    "unloaded_get",
    "single_tenant_interference",
    "two_tenant_interference",
)


def run_command(cmd: list[str]) -> None:
    print(" ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)


def find_free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def wait_for_port(
    port: int, process: subprocess.Popen, timeout_sec: float = 10.0
) -> None:
    deadline = time.time() + timeout_sec
    while time.time() < deadline:
        if process.poll() is not None:
            raise RuntimeError(
                f"mooncake_master exited with status {process.returncode}"
            )
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.settimeout(0.2)
            try:
                sock.connect(("127.0.0.1", port))
                return
            except OSError:
                time.sleep(0.1)
    raise TimeoutError(f"timed out waiting for mooncake_master on port {port}")


def start_master(
    master_binary: Path, output_dir: Path, scenario: str
) -> tuple[subprocess.Popen, int]:
    rpc_port = find_free_port()
    metrics_port = find_free_port()
    log_path = output_dir / f"master_{scenario}.log"
    log_file = log_path.open("w", encoding="utf-8")
    cmd = [
        str(master_binary),
        f"--rpc_port={rpc_port}",
        "--rpc_address=127.0.0.1",
        "--enable_metric_reporting=false",
        f"--metrics_port={metrics_port}",
        "--enable_http_metadata_server=false",
        "--enable_offload=false",
        "--enable_disk_eviction=false",
    ]
    print(" ".join(cmd), flush=True)
    process = subprocess.Popen(cmd, stdout=log_file, stderr=subprocess.STDOUT)
    try:
        wait_for_port(rpc_port, process)
    except Exception:
        process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=5)
        log_file.close()
        raise
    process._qos_log_file = log_file  # type: ignore[attr-defined]
    return process, rpc_port


def stop_master(process: subprocess.Popen) -> None:
    process.terminate()
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        process.kill()
        process.wait(timeout=5)
    log_file = getattr(process, "_qos_log_file", None)
    if log_file is not None:
        log_file.close()


def load_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def write_readme(output_dir: Path, binary: Path, args: argparse.Namespace) -> None:
    results = {
        "unloaded_get": load_json(output_dir / "baseline_get_only.json"),
        "single_tenant_interference": load_json(
            output_dir / "baseline_single_tenant.json"
        ),
        "two_tenant_interference": load_json(output_dir / "baseline_two_tenant.json"),
    }

    lines = [
        "# Tenant QoS Baseline Results",
        "",
        "Generated by `benchmarks/store_qos_baseline/run_baseline_qos_bench.py`.",
        "The benchmark uses the current baseline Store transfer path only; "
        "`TenantQosScheduler` is not wired into `Client::TransferData`.",
        "",
        "## Command",
        "",
        "```bash",
        " ".join(
            [
                str(binary),
                "--scenario=<scenario>",
                "--master_address=127.0.0.1:<runner-assigned-port>",
                f"--output_dir={output_dir}",
                "--protocol=tcp",
                f"--duration_sec={args.duration_sec}",
                f"--warmup_sec={args.warmup_sec}",
                f"--small_get_bytes={args.small_get_bytes}",
                f"--large_put_bytes={args.large_put_bytes}",
                f"--segment_bytes={args.segment_bytes}",
                f"--get_threads={args.get_threads}",
                f"--put_threads={args.put_threads}",
                f"--put_batch_size={args.put_batch_size}",
                f"--get_slo_ms={args.get_slo_ms}",
            ]
        ),
        "```",
        "",
        "## Summary",
        "",
        "| Scenario | Get p50 us | Get p95 us | Get p99 us | Get p999 us | "
        "SLO violation rate | Put MiB/s | Aggregate MiB/s |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for scenario in SCENARIOS:
        item = results[scenario]
        lines.append(
            "| {scenario} | {p50:.3f} | {p95:.3f} | {p99:.3f} | "
            "{p999:.3f} | {slo:.6f} | {put:.3f} | {agg:.3f} |".format(
                scenario=scenario,
                p50=item["get_p50_us"],
                p95=item["get_p95_us"],
                p99=item["get_p99_us"],
                p999=item["get_p999_us"],
                slo=item["get_slo_violation_rate"],
                put=item["put_mib_per_sec"],
                agg=item["aggregate_mib_per_sec"],
            )
        )

    lines.extend(
        [
            "",
            "## Files",
            "",
            "- `baseline_get_only.csv` / `.json`: Tenant B small Get without background Put.",
            "- `baseline_single_tenant.csv` / `.json`: same-tenant large Put plus small Get.",
            "- `baseline_two_tenant.csv` / `.json`: Tenant A large Put plus Tenant B small Get.",
        ]
    )
    (output_dir / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_combined_csv(output_dir: Path) -> None:
    json_files = [
        output_dir / "baseline_get_only.json",
        output_dir / "baseline_single_tenant.json",
        output_dir / "baseline_two_tenant.json",
    ]
    rows = [load_json(path) for path in json_files]
    if not rows:
        return
    with (output_dir / "baseline_summary.csv").open(
        "w", newline="", encoding="utf-8"
    ) as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run Mooncake Store QoS baseline scenarios"
    )
    parser.add_argument(
        "--binary",
        type=Path,
        default=Path("build/mooncake-store/tests/qos_baseline_benchmark"),
    )
    parser.add_argument(
        "--master-binary",
        type=Path,
        default=Path("build/mooncake-store/src/mooncake_master"),
    )
    parser.add_argument("--output-dir", type=Path, default=Path("qos_results"))
    parser.add_argument("--duration-sec", type=float, default=5.0)
    parser.add_argument("--warmup-sec", type=float, default=0.5)
    parser.add_argument("--small-get-bytes", type=int, default=1024 * 1024)
    parser.add_argument("--large-put-bytes", type=int, default=64 * 1024 * 1024)
    parser.add_argument("--segment-bytes", type=int, default=2 * 1024 * 1024 * 1024)
    parser.add_argument("--get-threads", type=int, default=1)
    parser.add_argument("--put-threads", type=int, default=1)
    parser.add_argument("--put-batch-size", type=int, default=1)
    parser.add_argument("--get-slo-ms", type=float, default=10.0)
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)
    for scenario in SCENARIOS:
        master_process, rpc_port = start_master(
            args.master_binary, args.output_dir, scenario
        )
        try:
            cmd = [
                str(args.binary),
                f"--scenario={scenario}",
                f"--master_address=127.0.0.1:{rpc_port}",
                f"--output_dir={args.output_dir}",
                "--protocol=tcp",
                f"--duration_sec={args.duration_sec}",
                f"--warmup_sec={args.warmup_sec}",
                f"--small_get_bytes={args.small_get_bytes}",
                f"--large_put_bytes={args.large_put_bytes}",
                f"--segment_bytes={args.segment_bytes}",
                f"--get_threads={args.get_threads}",
                f"--put_threads={args.put_threads}",
                f"--put_batch_size={args.put_batch_size}",
                f"--get_slo_ms={args.get_slo_ms}",
            ]
            run_command(cmd)
        finally:
            stop_master(master_process)

    write_combined_csv(args.output_dir)
    write_readme(args.output_dir, args.binary, args)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
